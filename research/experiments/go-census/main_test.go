func TestShapeAndPotentialAreNotEligibility(t *testing.T) {
	src := []byte("package main\nfunc sample() [2]int { a := 1; b := 2; return [2]int{a,b} }\n")
	got := scanFile("fixture.go", src)
	if !got.Parsed || len(got.Functions) != 1 || got.Functions[0].ShapeReason != "shape_match_only" || len(got.Runs) != 1 || got.Runs[0].Length != 2 {
		t.Fatalf("%+v", got)
	}
	if strings.Join(got.Functions[0].Gates, ",") != "source_build_scope_type_preconditions_unestablished" {
		t.Fatal(got.Functions[0].Gates)
	}
	otherPath := scanFile("ordinary.go", src)
	if strings.Join(otherPath.Functions[0].Gates, ",") != strings.Join(got.Functions[0].Gates, ",") {
		t.Fatal("parser filename label invented an eligibility gate")
	}
	malformed := scanFile("broken.go", []byte("package main\nfunc"))
	if malformed.Parsed || malformed.Error == "" || len(malformed.Functions) != 0 {
		t.Fatal("parser failure hidden")
	}
}
func TestLiteralBoundaryAndByteOffsets(t *testing.T) {
	src := []byte("package demo\n// ไทย café 🧵\nfunc work() { a := 1; b := 2; c := f(); d := 0x1; e := 2147483648; z := 3 }\n")
	got := scanFile("source.go", src)
	if len(got.Runs) != 2 || got.Runs[0].Length != 2 || got.Runs[1].Length != 1 || !got.Runs[0].NonASCIIprefix {
		t.Fatalf("%+v", got)
	}
	if string(src[got.Runs[0].Span.Start:got.Runs[0].Span.End]) != "a := 1; b := 2" {
		t.Fatal("not original UTF-8 byte interval")
	}
}
func TestExclusionsAndNoSymlinkTraversal(t *testing.T) {
	root := t.TempDir()
	outside := t.TempDir()
	for path, src := range map[string]string{
		"main.go":       "package main\nfunc main(){}",
		"main_test.go":  "package main\nfunc test(){}",
		"generated.go":  "// Code generated by synthetic. DO NOT EDIT.\npackage main\n",
		"vendor/x.go":   "package x\n",
		"testdata/x.go": "package x\n",
	} {
		full := filepath.Join(root, path)
		if err := os.MkdirAll(filepath.Dir(full), 0700); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(src), 0600); err != nil {
			t.Fatal(err)
		}
	}
	if err := os.WriteFile(filepath.Join(outside, "secret.go"), []byte("invalid"), 0600); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(outside, filepath.Join(root, "escape")); err != nil {
		t.Fatal(err)
	}
	sum, raw, err := scan(root, "testhash")
	if err != nil {
		t.Fatal(err)
	}
	if sum.GoFiles != 5 || sum.SkippedSymlinks != 1 || len(raw.Files) != 5 || sum.Classes["primary"].ExactEligible != 0 || sum.Classes["test"].Files != 1 || sum.Classes["generated"].Files != 1 || sum.Classes["dependency"].Files != 1 || sum.Classes["testdata"].Files != 1 {
		t.Fatalf("%+v", sum)
	}
}
