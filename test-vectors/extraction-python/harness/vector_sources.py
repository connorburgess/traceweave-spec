"""Hand-derived vector sources for py-tokens draft-1.

Each expected token stream below was written by hand from the profile text,
token by token; nothing here is produced by a lexer. build_vectors.py only
locates each token's span and computes k-grams, hashes and winnowing:
  * a token with text: the first occurrence of its text at or after the previous
    token's end (or the explicit code-point offset of a ("cls", text, offset) tuple);
  * NL (newline): zero-width at the first CR or LF at or after the previous
    token's end, or at the end of input if there is none;
  * IN / DE (indent / dedent): zero-width at the start of the next token with
    text, or at the end of input if there is none.
check_vectors.py then re-lexes every input with pylex.py and must agree.

Token syntax: "cls:text" with cls one of
  k keyword, i ident, p punct, n int, fl float, im imag, s string, y bytes,
  fs fstring-start, fm fstring-middle, fe fstring-end,
  ts tstring-start, tm tstring-middle, te tstring-end;
and the bare words NL, IN, DE.
Errors: E(code, offset) with the offset in code points (the builder converts
it to bytes); E_bytes for inputs that are not UTF-8.
"""

C = {"k": "keyword", "i": "ident", "p": "punct", "n": "int", "fl": "float", "im": "imag", "s": "string",
     "y": "bytes", "fs": "fstring-start", "fm": "fstring-middle", "fe": "fstring-end", "ts": "tstring-start",
     "tm": "tstring-middle", "te": "tstring-end"}
Z = {"NL": "newline", "IN": "indent", "DE": "dedent"}


def T(*items):
    out = []
    for it in items:
        if isinstance(it, tuple):
            out.append((Z[it[0]], None, it[2]) if it[0] in Z else (C[it[0]], it[1], it[2]))
        elif it in Z:
            out.append((Z[it], None, None))
        else:
            cls, _, text = it.partition(":")
            out.append((C[cls], text, None))
    return out


def E(code, offset):
    return ("error", code, offset)


def E_bytes(code, offset):
    return ("error-bytes", code, offset)


